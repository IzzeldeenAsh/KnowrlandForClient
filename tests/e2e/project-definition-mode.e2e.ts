test('expert-led request skips legacy required deliverables and keeps stale answers out of saves', { tags: ['project', 'phase3'], timeout: 120_000 }, async ({ app, screen, browser, projectApi }) => {
  projectApi.projectComponents = [{ id: 2, name: 'Target market', slug: 'target-market', ownership_level: 'project', definition_mode_visibility: 'both', is_required: false, fillable_by_insighter: true }];
  projectApi.serviceComponents = [{ id: 3, name: 'Deliverables', slug: 'deliverable-stage', ownership_level: 'project_service', definition_mode_visibility: 'both', is_required: true, fillable_by_insighter: false }];
  await app.open('/en/project/wizard/service');
  await browser.evaluate(() => {
    const prefix = 'project:wizard:en:';
    Object.entries({ projectType: 'ad_hoc', deliverablesLanguage: 'English', insighterIndustryId: '8', projectStatus: 'idea stage', whoAreYou: 'startup', preferredInsighterType: 'Either', plannedStartDate: '2027-01-01', durationDays: '30' }).forEach(([key, value]) => sessionStorage.setItem(prefix + key, value));
    return null;
  });
  await screen.getByRole('radio', /^Market research/).tap();
  await expect(browser).toHaveURL('/en/project/wizard/definition-mode');
  await expect(screen.getByRole('radio', 'Let the expert propose it')).toBeChecked();
  expect(projectApi.calls.filter(call => call.path.includes('/definition/initiate'))).toHaveLength(0);
  await app.screenshot('project-requirements-choice');
  await screen.getByRole('link', 'Back').tap();
  await expect(browser).toHaveURL('/en/project/wizard/service');
  await expect(screen.getByRole('radio', /^Market research/)).toBeChecked();
  await screen.getByRole('button', 'Continue').tap();
  await expect(browser).toHaveURL('/en/project/wizard/definition-mode');
  projectApi.failInitiateOnce = true;
  await screen.getByRole('button', 'Continue').tap();
  await expect(screen.getByText('Could not create the request. Please retry.').first()).toBeVisible();
  await expect(screen.getByRole('radio', 'Let the expert propose it')).toBeChecked();
  expect(await browser.evaluate(() => sessionStorage.getItem('project:wizard:en:projectUuid'))).toBe(null);
  await screen.getByRole('button', 'Continue').tap();
  await expect(browser).toHaveURL('/en/project/wizard/target-market');
  expect(projectApi.calls.find(call => call.path.includes('/setting/service/component/'))?.path).toBe('/api/common/setting/service/component/1');
  // A resumed browser may still have the former deliverables step and answer.
  await browser.evaluate(() => {
    sessionStorage.setItem('project:wizard:en:serviceComponentSlugs', JSON.stringify(['deliverables-plan']));
    sessionStorage.setItem('project:wizard:en:projectComponentSlugs', JSON.stringify(['target-market', 'deliverable-stage']));
    sessionStorage.setItem('project:wizard:en:serviceComponentsPayload', JSON.stringify({ components: { 'deliverable-stage': { deliverables: [{ title: 'Stale client deliverable', period_days: 30 }] } } }));
    return null;
  });
  await screen.getByRole('button', 'Let the Insighter define this').tap();
  await expect(browser).toHaveURL('/en/project/wizard/project-description');
  expect(projectApi.calls.find(call => call.path.endsWith('/definition/initiate'))?.body).toMatchObject({ definition_mode: 'simple', service_id: 1, insighter_industry_id: 8 });
  expect(projectApi.calls.filter(call => call.path.includes('/scope/'))).toHaveLength(0);
  const properties = projectApi.calls.find(call => call.path.includes('/properties/sync/'))?.body;
  expect(properties).not.toHaveProperty('definition_mode');
  expect(properties?.components).toEqual({});
  expect(projectApi.calls.filter(call => call.path.includes('/definition/component/sync/'))).toHaveLength(0);
  await app.open('/en/project/wizard/deliverables-plan');
  await expect(browser).toHaveURL('/en/project/wizard/target-market');
  await expect(screen.getByLabel('Deliverable name')).toHaveCount(0);
  await app.open('/en/project/wizard/project-scope');
  await expect(browser).toHaveURL('/en/project/wizard/target-market');
  expect(projectApi.calls.filter(call => call.path.includes('/scope/'))).toHaveLength(0);
  await app.open('/en/project/wizard/definition-mode');
  await expect(screen.getByRole('radio', 'Define it myself')).toBeDisabled();
  await screen.getByRole('button', 'Continue').tap();
  await expect(browser).toHaveURL('/en/project/wizard/target-market');
  expect(projectApi.calls.filter(call => call.path.includes('/definition/initiate'))).toHaveLength(2);
  expect(await browser.evaluate(() => sessionStorage.getItem('project:wizard:en:definitionMode'))).toBe('simple');
  expect(projectApi.unexpected).toEqual([]);
  expect(await browser.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test('expert-led AI request keeps clarification but never displays suggested scopes', { tags: ['project', 'phase3'], timeout: 120_000 }, async ({ app, screen, browser, projectApi }) => {
  projectApi.projectComponents = [];
  projectApi.serviceComponents = [{ id: 3, name: 'Deliverables', slug: 'deliverables-stage', is_required: true }];
  projectApi.aiNeedsAnswers = true;
  await app.open('/en/project/wizard/service');
  await screen.getByRole('textbox').fill('Assess demand for consulting services in Jordan.');
  await screen.getByRole('button', 'Clarify request').tap();
  await expect(browser).toHaveURL('/en/project/wizard/definition-mode');
  expect(projectApi.calls.filter(call => call.path.includes('/definition/initiate'))).toHaveLength(0);
  await screen.getByRole('button', 'Continue').tap();
  await expect(browser).toHaveURL('/en/project/wizard/ai-intake');
  await expect(screen.getByText('Which market?')).toBeVisible();
  await screen.getByRole('textbox').fill('Jordan');
  await screen.getByRole('button', 'Send answers').tap();
  await expect(browser).toHaveURL('/en/project/wizard/project-description', { timeout: 30_000 });
  await expect(screen.getByRole('heading', 'Select AI-suggested project scopes')).toHaveCount(0);
  expect(projectApi.calls.find(call => call.path.endsWith('/definition/initiate'))?.body).toMatchObject({ definition_mode: 'simple', service_id: 3, prompt_ai: 'Assess demand for consulting services in Jordan.' });
  expect(projectApi.calls.find(call => call.path.includes('/ai-intake/answers/'))?.body.answers).toEqual([{ key: 'market', answer: 'Jordan' }]);
  expect(projectApi.calls.filter(call => call.path.includes('/scope/'))).toHaveLength(0);
  expect(projectApi.unexpected).toEqual([]);
});

test('client-defined scope retries preserve selections and required deliverables remain required', { tags: ['project', 'phase3'], timeout: 120_000 }, async ({ app, screen, browser, projectApi }) => {
  projectApi.projectComponents = [];
  projectApi.serviceComponents = [{ id: 3, name: 'Deliverables', slug: 'deliverable-stage', ownership_level: 'project_service', definition_mode_visibility: 'advanced', is_required: true, fillable_by_insighter: true }];
  await app.open('/en/project/wizard/service');
  await screen.getByRole('radio', /^Market research/).tap();
  await expect(browser).toHaveURL('/en/project/wizard/definition-mode');
  await screen.getByRole('radio', 'Define it myself').tap();
  await browser.reload();
  await expect(screen.getByRole('radio', 'Define it myself')).toBeChecked();
  expect(projectApi.calls.filter(call => call.path.includes('/definition/initiate'))).toHaveLength(0);
  await screen.getByRole('button', 'Continue').tap();
  await expect(browser).toHaveURL('/en/project/wizard/project-scope');
  await expect(screen.getByRole('button', 'Let the expert propose the scope')).toHaveCount(0);
  await expect(screen.getByRole('button', 'Continue')).toBeDisabled();
  await screen.getByRole('checkbox', 'Analysis').check();
  await screen.getByRole('button', 'Continue').tap();
  await expect(browser).toHaveURL('/en/project/wizard/project-subscopes');
  await screen.getByRole('button', 'Market size').tap();
  projectApi.failScopeOnce = true;
  await screen.getByRole('button', 'Continue').tap();
  await expect(screen.getByText('Could not save the scope choice. Please retry.').first()).toBeVisible();
  await expect(browser).toHaveURL('/en/project/wizard/project-subscopes');
  await expect(screen.getByRole('button', 'Market size')).toHaveAttribute('aria-pressed', 'true');
  await screen.getByRole('button', 'Continue').tap();
  await expect(browser).toHaveURL('/en/project/wizard/deliverables-plan');
  await expect(screen.getByRole('button', 'Let the Insighter define this')).toHaveCount(0);
  await screen.getByRole('button', 'Continue').tap();
  await expect(screen.getByText('Enter a name for this deliverable.')).toBeVisible();
  await screen.getByLabel('Deliverable name').fill('Market opportunity report');
  await screen.getByRole('button', 'Due date').tap();
  await screen.getByRole('spinbutton', 'Days from project start').fill('7');
  await screen.getByRole('spinbutton', 'Days from project start').press('Escape');
  await screen.getByRole('button', 'File format').tap();
  await screen.getByRole('option', 'PDF Report').tap();
  await screen.getByRole('option', 'PDF Report').press('Escape');
  await screen.getByRole('button', 'Delivery method').tap();
  await screen.getByRole('option', 'On platform').tap();
  await screen.getByRole('button', 'Continue').tap();
  await expect(browser).toHaveURL('/en/project/wizard/project-description');
  expect(projectApi.calls.filter(call => call.path.includes('/definition/initiate'))).toHaveLength(1);
  const scopeSaves = projectApi.calls.filter(call => call.path.includes('/scope/sync/'));
  expect(scopeSaves).toHaveLength(2);
  for (const call of scopeSaves) {
    expect(call.raw).toContain('Analysis');
    expect(call.raw).toContain('Market size');
  }
  expect(await browser.evaluate(() => sessionStorage.getItem('project:wizard:en:definitionMode'))).toBe('advanced');
  expect(projectApi.unexpected).toEqual([]);
});

